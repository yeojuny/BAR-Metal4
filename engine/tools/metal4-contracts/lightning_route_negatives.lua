for _,target in ipairs({'LuaRules/Gadgets/gfx_lightning_cannon_gl4.lua','LuaRules/Gadgets/gfx_environmental_lightning_gl4.lua'})do
 local source=gl.NativeLightning.LoadArchiveSource(target)
 local processed=gl.NativeLightning.PrepareSource(source)
 FixtureCheck(type(processed)=='string' and #processed>0,'pinned raw bytes accepted by real Tracy preprocessing')
 FixtureCheck(VFS.LoadFile(target,VFS.ZIP_ONLY)==processed,'ordinary unrelated caller gets original archive')
 local stale=assert(loadstring('return function()return VFS.LoadFile("'..target..'",VFS.ZIP_ONLY)end','LuaRules/gadgets.lua'))()
 FixtureCheck(stale()==processed,'wrong caller extent cannot acquire native route')
 FixtureSetRouteFaults(false,true)
 local ok,why=pcall(function()FixtureHandler:LoadGadget(target)end)
 FixtureCheck(not ok and string.find(why,'handler identity changed',1,true)~=nil,'actual loader rejects stale original handler')
 FixtureSetRouteFaults(true,false)
 ok,why=pcall(function()FixtureHandler:LoadGadget(target)end)
 FixtureCheck(not ok and string.find(why,'Staged native effect adapter is missing',1,true)~=nil,'missing adapter fails explicitly')
 FixtureSetRouteFaults(false,false)
 FixtureSyncLoader(true);FixtureClearLoads()
 FixtureCheck(FixtureHandler:LoadGadget(target)==nil,'synced loader cannot get private native adapter')
 FixtureCheck(FixtureRawLoads()==0,'synced loader does not read RAW adapter')
 FixtureSyncLoader(false)
 FixtureCheck(not pcall(function()gl.NativeLightning.PrepareSource(source..'changed')end),'changed archive is rejected')
end
FixtureClearLoads()
FixtureCheck(FixtureHandler:LoadGadget('LuaRules/Gadgets/unrelated.lua')==nil,'unrelated missing archive remains ordinary missing load')
FixtureCheck(FixtureRawLoads()==0,'unrelated path does not read RAW')
FixtureCheck(not pcall(function()gl.NativeLightning.LoadArchiveSource('arbitrary.lua')end),'unrelated source rejected')
